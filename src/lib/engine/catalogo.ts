export const CATALOGO_SERVICOS: readonly ServicoCatalogo[] = ETAPAS.flatMap((e, ie) =>
  GRUPOS[e.id].map(([chave, descricao, unidade, bdi], i) => ({
    chave, descricao, unidade, etapa: e.id, ordem: (ie + 1) * 1000 + i + 1, bdi: bdi ?? "servico",
  })),
);

const POR_CHAVE = new Map(CATALOGO_SERVICOS.map((s) => [s.chave, s]));

export function servicoDoCatalogo(chave: string): ServicoCatalogo {
  const s = POR_CHAVE.get(chave);
  if (!s) throw new Error(`Chave de serviço fora do catálogo: ${chave}`);
  return s;
}

export function nomeEtapa(id: string): string {
  return ETAPAS.find((e) => e.id === id)?.nome ?? id;
}
